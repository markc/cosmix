    fn version_repo() -> (tempfile::TempDir, PathBuf, String) {
        let tmp = tempfile::tempdir().unwrap();
        let repo = tmp.path().join("repo");
        std::fs::create_dir(&repo).unwrap();
        git(&repo, &["init", "-b", "main"]).unwrap();
        git(&repo, &["config", "user.name", "test"]).unwrap();
        git(&repo, &["config", "user.email", "test@example.com"]).unwrap();
        std::fs::create_dir_all(repo.join("crate/src")).unwrap();
        std::fs::write(
            repo.join("Cargo.toml"),
            "[workspace]\nmembers=['crate']\n[workspace.package]\nversion='0.1.0'\n",
        )
        .unwrap();
        std::fs::write(
            repo.join("crate/Cargo.toml"),
            "[package]\nname='fixture'\nversion.workspace=true\nedition='2024'\n",
        )
        .unwrap();
        std::fs::write(repo.join("crate/src/lib.rs"), "pub fn base() {}\n").unwrap();
        std::fs::write(
            repo.join("Cargo.lock"),
            "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\n",
        )
        .unwrap();
        git(&repo, &["add", "."]).unwrap();
        git(&repo, &["commit", "-m", "base"]).unwrap();
        let base = git(&repo, &["rev-parse", "HEAD"])
            .unwrap()
            .trim()
            .to_string();
        (tmp, repo, base)
    }

