    let db = tmp.path().join("ledger.db");
    let ledger = Ledger::open(&db).unwrap();

    // Bank real spend ABOVE the ceiling, the way an overshooting run does.
    let task = ledger
        .add_task("t", "spec", "impl", "low", &[], "none")
        .unwrap();
    let run = ledger
        .start_run(task, AgentKind::Claude, None, None)
        .unwrap();
    ledger
        .finish_run(
            run,
            &RunOutcome {
                stop: StopReason::Done,
                result: None,
                error: None,
                usage: Usage {
                    input_tokens: 0,
                    fresh_input_tokens: None,
                    output_tokens: 10,
                    cost_usd: Some(12.0),
                    cache_read_input_tokens: None,
                    cache_creation_input_tokens: None,
                },
                session_ref: None,
                terminal_session_ref: None,
                usage_observed: true,
                output_observed: true,
                resume_failure: None,
            },
            1,
        )
        .unwrap();

    let governor = Governor::with_limits(&db, 10.0, 1_000_000);
