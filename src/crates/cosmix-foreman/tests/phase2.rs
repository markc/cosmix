// ---- reservation ----

/// The free lane must not be gated by the metered lane's ceiling.
///
/// The runner discards `cost_usd` for GLM (the claude CLI prices remapped
/// Z.ai traffic at Anthropic rates, which is fiction), so a GLM run can
/// never spend a cent against the dollar ceiling. Reserving dollars for it
/// anyway means that once the claude lane fills the ceiling, the free lane
/// is refused too and the fleet stops completely.
///
/// Observed live 2026-08-19: at $96.43 of a $100 ceiling, dispatch routed
/// tasks 9 and 10 to glm and both were refused with "$96.43 spent + $5.00
/// requested exceeds the $100.00 daily ceiling". Nothing ran for the rest
/// of the UTC day.
#[test]
fn free_lane_is_not_gated_by_the_dollar_ceiling() {
    let tmp = tempfile::tempdir().unwrap();
    let db = tmp.path().join("ledger.db");
    let ledger = Ledger::open(&db).unwrap();
    let governor = Governor::with_limits(&db, 10.0, 1_000_000);

    // Fill the dollar ceiling with a metered hold.
    let full = Budget {
        max_budget_usd: Some(10.0),
        max_output_tokens: Some(1_000),
        ..Default::default()
    };
    governor
        .reserve(&ledger, "claude@1", Some(1), &full, AgentKind::Claude)
        .expect("the metered hold itself fits");

    // A metered run now has no room — the ceiling is doing its job.
    let err = governor
        .reserve(&ledger, "claude@2", Some(2), &full, AgentKind::Claude)
        .unwrap_err();
    assert!(
        format!("{err:#}").contains("reservation refused"),
        "the dollar ceiling must still bind the metered lane: {err:#}"
    );

    // The unmetered lanes must still be admitted at the same instant.
    //
    // An EXPLICIT non-zero cap is used deliberately rather than
    // `Budget::default()`: the default reserve is configurable through the
    // governor's policy snapshot, so pinning $6 keeps this test independent
    // of that separate mechanism.
    // Token holds are pinned small and explicit so this test can only ever
    // fail on the DOLLAR dimension; left at the env default, three holds
    // collide with the token ceiling and the refusal has nothing to do with
    // what is under test.
    let asks_six = Budget {
        max_budget_usd: Some(6.0),
        max_output_tokens: Some(1_000),
        ..Default::default()
    };
    for (who, kind) in [("glm@3", AgentKind::Glm), ("codex@4", AgentKind::Codex)] {
        governor
            .reserve(&ledger, who, Some(3), &asks_six, kind)
            .unwrap_or_else(|e| panic!("{who} must run while the metered ceiling is full: {e:#}"));
    }

    // And they must hold no dollars, or a queue of them would gate each
    // other. Exactly $10 also refutes "reserve $0 for everyone": under that
    // implementation the claude@2 refusal above would not have happened.
    let s = governor.status(&ledger).unwrap();
    assert!(
        (s.reserved_usd - 10.0).abs() < 1e-9,
        "the free lanes must reserve $0, got total {:?}",
        s.reserved_usd
    );
}

/// Requesting $0 is not enough — the dollar dimension must be OFF.
///
/// The ledger's test is `spent + held + requested > ceiling`, so once spend
/// sits ABOVE the ceiling even a $0 request is refused and the free lane
/// halts again. Spend gets there routinely: a lowered ceiling, a
/// `--no-governor` run, or actuals overshooting their hold (live run 81 cost
/// $5.09 against a $5 hold). Found by the codex review arm 2026-08-19 as the
/// residual left by the first cut of the fix.
