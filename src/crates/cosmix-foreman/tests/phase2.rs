#[test]
fn policy_refuses_manifest_edit_outside_task_crate_scope() {
    let repo = PolicyRepo::new();
    let c = repo.ctx(&["own-crate"]);
    let own = repo.path("src/crates/own-crate/Cargo.toml");
    let other = repo.path("src/crates/other-crate/Cargo.toml");
    let proposed = OWN_MANIFEST.replace("anyhow = \"1\"", "anyhow = \"2\"");

    // Uncommitted work cannot widen authority between tool calls.
    std::fs::write(
        repo.path("src/crates/own-crate/src/lib.rs"),
        "pub const NAME: &str = \"changed by task\";\n",
    )
    .unwrap();
    let branch_scoped = repo.ctx(&[]);
    let uncommitted = evaluate(
        &branch_scoped,
        &call("Write", json!({"file_path": &own, "content": &proposed})),
    );
    assert!(
        matches!(&uncommitted, Verdict::Escalate(reason) if reason.contains("commit your change")),
        "uncommitted change must not widen crate scope: {uncommitted:?}"
    );

    // Once the non-manifest work is durable in branch history, the task need
    // not repeat the crate name through operator-owned scope.
    run_git(&repo.root, &["add", "src/crates/own-crate/src/lib.rs"]);
    run_git(&repo.root, &["commit", "-m", "change own crate"]);
    assert_eq!(
        evaluate(
            &branch_scoped,
            &call("Write", json!({"file_path": &own, "content": &proposed}))
        ),
        Verdict::Allow
    );

    // The same dependency edit is refused when the task does not own the crate.
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({
                    "file_path": &other,
                    "content": format!("{OTHER_MANIFEST}\n[dependencies]\nserde = \"1\"\n")
                })
            )
        ),
        Verdict::Escalate(_)
    ));

    // Free-form prose has no authority. A task saying "do not modify
    // other-crate" must not authorise other-crate's manifest.
    let prose_only = repo.ctx(&[]);
    assert!(matches!(
        evaluate(
            &prose_only,
            &call(
                "Write",
                json!({
                    "file_path": &other,
                    "content": format!("{OTHER_MANIFEST}\n[dependencies]\nserde = \"1\"\n")
                })
            )
        ),
        Verdict::Escalate(_)
    ));
}

