/// The resume argv shapes handed to the REAL vendor CLIs must parse.
///
/// A shape assertion cannot see a clap rejection: the first cut of task 70's
/// codex resume put `--sandbox`/`--add-dir` after the `exec resume`
/// subcommand, which reads perfectly as a string vector and is refused
/// outright by codex-cli ("error: unexpected argument '--sandbox' found").
/// So this drives the installed binary and asserts only that argv PARSING
/// succeeded — the run is deliberately made to die immediately afterwards on
/// codex's own trusted-directory check by giving it a non-repo cwd, so the
/// test costs no tokens and touches no network.
///
/// Skipped when the binary is absent (developer machines, CI images without
/// the vendor CLI), and when the child does not exit promptly — an
/// environment quirk must not turn into a red test.
#[test]
fn codex_resume_argv_is_accepted_by_the_installed_cli() {
    let Some(codex_bin) = which("codex") else {
        eprintln!("codex not installed; skipping the real-parser gate");
        return;
    };
    let tmp = tempfile::tempdir().unwrap();
    // Grants are computed against a real repo; the CWD deliberately is not
    // one, so codex refuses on the trusted-directory check AFTER parsing.
    let repo = tmp.path().join("repo");
    std::fs::create_dir(&repo).unwrap();
    std::process::Command::new("git")
        .args(["init", "-q"])
        .current_dir(&repo)
        .status()
        .unwrap();
    let not_a_repo = tmp.path().join("elsewhere");
    std::fs::create_dir(&not_a_repo).unwrap();

    let args = CodexDriver::new()
        .with_model(Some("gpt-5.6-sol".into()))
        .resume_args_for(
            "00000000-0000-0000-0000-000000000000",
            "re-judge your findings",
            &Budget::default(),
            &repo,
        );
    let mut child = std::process::Command::new(&codex_bin)
        .args(&args)
        .current_dir(&not_a_repo)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .unwrap();
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(30);
    loop {
        match child.try_wait().unwrap() {
            Some(_) => break,
            None if std::time::Instant::now() >= deadline => {
                let _ = child.kill();
                let _ = child.wait();
                eprintln!("codex did not exit promptly; skipping the real-parser gate");
                return;
            }
            None => std::thread::sleep(std::time::Duration::from_millis(50)),
        }
    }
    let out = child.wait_with_output().unwrap();
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        !text.contains("unexpected argument") && !text.contains("Usage: codex exec"),
        "codex refused the resume argv at parse time.\nargv: {args:?}\noutput: {text}"
    );
}

fn which(program: &str) -> Option<std::path::PathBuf> {
    std::env::var_os("PATH").and_then(|path| {
        std::env::split_paths(&path)
            .map(|dir| dir.join(program))
            .find(|candidate| candidate.is_file())
    })
}

/// `meters_dollars()` must agree with each lane's driver, which is the
/// ground truth for "does a real dollar figure exist here".
///
/// The first cut of this predicate was derived from the GLM incident rather
/// than from the drivers, and shipped green with `Codex => true` — a phantom
/// $5 hold on a lane that reports no cost at all. Both review arms caught it
/// independently; this test is what stops the next lane repeating it.
#[test]
fn lane_metering_matches_drivers() {
    // Built directly rather than through `driver::build`, which resolves a
    // real Z.ai token for the GLM lane; the capability answer does not
    // depend on the credential.
    let drivers: Vec<(AgentKind, Box<dyn Executor>)> = vec![
        (AgentKind::Claude, Box::new(ClaudeDriver::new())),
        (AgentKind::Glm, Box::new(ClaudeDriver::glm("test-token"))),
        (AgentKind::Codex, Box::new(CodexDriver::new())),
    ];
    for (kind, driver) in drivers {
        assert_eq!(
            kind,
            driver.kind(),
            "test wired the wrong driver for {}",
            kind.as_str()
        );
        assert_eq!(
            kind.meters_dollars(),
            driver.capabilities().enforces_cost_cap,
            "{}: meters_dollars() disagrees with its driver's \
             enforces_cost_cap — one of them is lying about whether this \
             lane can produce a dollar figure",
            kind.as_str()
        );
    }
}

/// Token holds are real for every lane — the fix above must not have
/// exempted the free lane from the token ceiling as a side effect.
#[test]
fn free_lane_still_holds_tokens() {
    let tmp = tempfile::tempdir().unwrap();
    let db = tmp.path().join("ledger.db");
    let ledger = Ledger::open(&db).unwrap();
    let governor = Governor::with_limits(&db, 10.0, 600_000);

    // EXPLICIT token caps, not `Budget::default()`: the default reserve is
    // configurable through the governor's policy snapshot. 400k x 2 > 600k
    // regardless of that separate mechanism.
    let asks_400k = Budget {
        max_output_tokens: Some(400_000),
        ..Default::default()
    };

    governor
        .reserve(&ledger, "glm@1", Some(1), &asks_400k, AgentKind::Glm)
        .expect("first free-lane hold fits");
    let s = governor.status(&ledger).unwrap();
    assert_eq!(
        s.reserved_tokens, 400_000,
        "the free lane must still hold output tokens: {s:?}"
    );

    // The second hold crosses the 600k ceiling → refused on TOKENS, proving
    // the free lane is still governed. Asserting the DISTINGUISHING text,
    // not just "reservation refused": the dollar dimension is off for this
    // lane, so a refusal naming dollars would mean the fix leaked.
    let err = governor
        .reserve(&ledger, "glm@2", Some(2), &asks_400k, AgentKind::Glm)
        .unwrap_err();
    let err = format!("{err:#}");
    assert!(
        err.contains("output tokens"),
        "the token ceiling must still bind the free lane: {err}"
    );
}

#[test]
fn reservation_holds_headroom_atomically() {
    let tmp = tempfile::tempdir().unwrap();
    let db = tmp.path().join("ledger.db");
    let ledger = Ledger::open(&db).unwrap();
    let governor = Governor::with_limits(&db, 10.0, 1_000_000);

    // First run reserves its explicit cap.
    let budget_a = Budget {
        max_budget_usd: Some(6.0),
        ..Default::default()
    };
    let a = governor
        .reserve(&ledger, "w1", Some(1), &budget_a, AgentKind::Claude)
        .unwrap();

    // A second identical hold would exceed the $10 ceiling → refused, even
    // though nothing has been SPENT yet.
    let err = governor
        .reserve(&ledger, "w2", Some(2), &budget_a, AgentKind::Claude)
        .unwrap_err();
    assert!(
        format!("{err:#}").contains("reservation refused"),
        "{err:#}"
    );

    // A smaller hold still fits.
    let budget_b = Budget {
        max_budget_usd: Some(3.0),
        ..Default::default()
    };
    let b = governor
        .reserve(&ledger, "w2", Some(2), &budget_b, AgentKind::Claude)
        .unwrap();

    // Status shows both holds; admit (the MCP gate) sees them too.
    let s = governor.status(&ledger).unwrap();
    assert!((s.reserved_usd - 9.0).abs() < 1e-9, "{s:?}");
    let err = format!("{:#}", governor.admit(&ledger).unwrap_err());
    assert!(err.contains("reserved"), "{err}");

    // Releases free the headroom.
    governor.release(&ledger, a).unwrap();
    governor.release(&ledger, b).unwrap();
    governor.admit(&ledger).unwrap();
    governor.release(&ledger, a).expect("release is idempotent");
}

fn insert_reservation(
    db: &std::path::Path,
    claimant: &str,
    usd: f64,
    tokens: i64,
    pid: Option<i64>,
    pid_start: Option<i64>,
    created_at: &str,
) {
    let conn = rusqlite::Connection::open(db).unwrap();
    conn.execute(
        "INSERT INTO reservations
             (claimant, task_id, usd, tokens, pid, pid_start, created_at)
         VALUES (?1, NULL, ?2, ?3, ?4, ?5, ?6)",
        rusqlite::params![claimant, usd, tokens, pid, pid_start, created_at],
    )
    .unwrap();
}

#[test]
fn governor_status_and_reserve_sweep_young_dead_pid_reservations() {
    let tmp = tempfile::tempdir().unwrap();
    let db = tmp.path().join("ledger.db");
    let ledger = Ledger::open(&db).unwrap();
    let governor = Governor::with_limits(&db, 10.0, 1_000_000);
    let now = chrono::Utc::now().to_rfc3339();

    // Deliberately younger than the four-hour fallback. The impossible pid
    // makes the owner absence deterministic without depending on pid reuse.
    insert_reservation(
        &db,
        "dead-before-status",
        9.0,
        900_000,
        Some(999_999_999),
        None,
        &now,
    );
    let status = governor.status(&ledger).unwrap();
    assert_eq!(
        status.reserved_usd, 0.0,
        "status must sweep a young dead hold"
    );
    assert_eq!(status.reserved_tokens, 0);

    // Plant another young dead hold after status, so reserve's independent
    // call site must widen its sweep too. Without that sweep, 9 + 9 exceeds
    // the $10 ceiling and this request is refused.
    insert_reservation(
        &db,
        "dead-before-reserve",
        9.0,
        900_000,
        Some(999_999_999),
        None,
        &chrono::Utc::now().to_rfc3339(),
    );
    let id = governor
        .reserve(
            &ledger,
            "live",
            None,
            &Budget {
                max_budget_usd: Some(9.0),
                max_output_tokens: Some(900_000),
                ..Default::default()
            },
            AgentKind::Claude,
        )
        .expect("reserve must clear a young dead hold before checking headroom");
    governor.release(&ledger, id).unwrap();
}

#[test]
fn reservation_sweep_keeps_a_long_running_owner_and_fences_pid_reuse() {
    let tmp = tempfile::tempdir().unwrap();
    let db = tmp.path().join("ledger.db");
    let ledger = Ledger::open(&db).unwrap();
    let governor = Governor::with_limits(&db, 10.0, 1_000_000);
    let pid = std::process::id() as i64;
    let pid_start = cosmix_foreman::procutil::starttime(pid).expect("test pid has /proc stat");
    let old = (chrono::Utc::now() - chrono::Duration::hours(5)).to_rfc3339();

    // Old enough for the TTL arm, but held by this still-running process.
    insert_reservation(
        &db,
        "live-long-run",
        4.0,
        400_000,
        Some(pid),
        Some(pid_start),
        &old,
    );
    // Same numeric pid, different process generation: this represents the
    // stale hold left before a pid was recycled. pid_start, not pid alone,
    // must stop that dead generation pinning headroom.
    insert_reservation(
        &db,
        "reused-pid-generation",
        3.0,
        300_000,
        Some(pid),
        Some(pid_start + 1),
        &chrono::Utc::now().to_rfc3339(),
    );

    let status = governor.status(&ledger).unwrap();
    assert_eq!(status.reserved_usd, 4.0);
    assert_eq!(status.reserved_tokens, 400_000);
    let conn = rusqlite::Connection::open(&db).unwrap();
    let remaining: Vec<String> = conn
        .prepare("SELECT claimant FROM reservations ORDER BY claimant")
        .unwrap()
        .query_map([], |row| row.get(0))
        .unwrap()
        .collect::<Result<_, _>>()
        .unwrap();
    assert_eq!(remaining, vec!["live-long-run"]);
}

#[test]
fn terminal_unpriced_orphan_spend_uses_its_recorded_dollar_reservation() {
    let tmp = tempfile::tempdir().unwrap();
    let db = tmp.path().join("ledger.db");
    let ledger = Ledger::open(&db).unwrap();
    let task = ledger
        .add_task("unpriced orphan", "spec", "impl", "low", &[], "none")
        .unwrap();
    let run = ledger
        .start_run(task, AgentKind::Claude, None, None)
        .unwrap();
    let conn = rusqlite::Connection::open(&db).unwrap();
    conn.execute("UPDATE runs SET reserved_usd = 4.25 WHERE id = ?1", [run])
        .unwrap();
    ledger
        .update_run_usage(
            run,
            &Usage {
                input_tokens: 1200,
                output_tokens: 300,
                cost_usd: None,
                ..Usage::default()
            },
        )
        .unwrap();

    let since = "2000-01-01T00:00:00+00:00";
    assert_eq!(
        conn.query_row("SELECT cost_usd FROM runs WHERE id = ?1", [run], |row| {
            row.get::<_, Option<f64>>(0)
        },)
            .unwrap(),
        None,
        "the regression fixture must genuinely leave cost_usd NULL",
    );
    assert_eq!(
        ledger.usage_since(since).unwrap(),
        (0.0, 300),
        "an open production run is still covered by its live reservation"
    );

    // The orphan reaper terminalises this shape without inventing a price.
    // Preserve that exact NULL while marking the run terminal.
    conn.execute(
        "UPDATE runs SET verdict = 'error', delivery = 'harness_error',
                         error = 'claim owner died'
         WHERE id = ?1",
        [run],
    )
    .unwrap();
    assert_eq!(
        conn.query_row("SELECT cost_usd FROM runs WHERE id = ?1", [run], |row| {
            row.get::<_, Option<f64>>(0)
        },)
            .unwrap(),
        None,
        "terminalisation must not turn an unknown price into zero or a fixture cost",
    );

    let governor = Governor::with_limits(&db, 5.0, 1_000_000);
    let status = governor.status(&ledger).unwrap();
    assert_eq!(status.spend_today_usd, 4.25);
    assert_eq!(status.output_tokens_today, 300);
    let error = governor
        .reserve(
            &ledger,
            "next-run",
            Some(task),
            &Budget {
                max_budget_usd: Some(1.0),
                max_output_tokens: Some(1),
                ..Default::default()
            },
            AgentKind::Claude,
        )
        .unwrap_err();
    assert!(
        format!("{error:#}").contains("$4.25 spent"),
        "the atomic reserve check must use the same orphan charge as status: {error:#}"
    );
}

