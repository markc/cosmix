impl PolicyRepo {
    fn new() -> Self {
        let temp = tempfile::tempdir().unwrap();
        let root = temp.path().to_path_buf();
        for crate_name in ["own-crate", "other-crate"] {
            std::fs::create_dir_all(root.join("src/crates").join(crate_name).join("src")).unwrap();
            std::fs::write(
                root.join("src/crates").join(crate_name).join("src/lib.rs"),
                format!("pub const NAME: &str = {crate_name:?};\n"),
            )
            .unwrap();
        }
        std::fs::write(root.join("src/crates/own-crate/Cargo.toml"), OWN_MANIFEST).unwrap();
        std::fs::create_dir_all(root.join("desktop/crates/own-crate")).unwrap();
        std::fs::write(
            root.join("desktop/crates/own-crate/Cargo.toml"),
            OWN_MANIFEST,
        )
        .unwrap();
        std::fs::write(
            root.join("src/crates/other-crate/Cargo.toml"),
            OTHER_MANIFEST,
        )
        .unwrap();
        std::fs::write(root.join("src/Cargo.lock"), TEST_LOCK).unwrap();
        // Deliberately no `main`: policy scope must use the caller-resolved
        // integration base, never a hard-coded branch name.
        run_git(&root, &["init", "-b", "integration"]);
        run_git(&root, &["config", "user.email", "fixture@example.com"]);
        run_git(&root, &["config", "user.name", "Policy Fixture"]);
        run_git(&root, &["add", "."]);
        run_git(&root, &["commit", "-m", "fixture"]);
        run_git(&root, &["checkout", "-b", "task/7"]);
        Self { _temp: temp, root }
    }

    fn ctx(&self, crates: &[&str]) -> PolicyContext {
        let integration_base = git_stdout(&self.root, &["rev-parse", "integration"]);
        PolicyContext {
            task_id: 7,
            worktree: self.root.clone(),
            branch: Some("task/7".into()),
            provider: "anthropic".into(),
            integration_base,
            integration_branch: "integration".into(),
            task_ref_template: "task/{id}".into(),
            package_manifest_template: Some("src/crates/{crate}/Cargo.toml".into()),
            restrict_manifest_edits: false,
            task_crates: crates.iter().map(|name| (*name).to_string()).collect(),
        }
    }

    fn path(&self, relative: &str) -> String {
        self.root.join(relative).to_string_lossy().into_owned()
    }
}

fn run_git(dir: &std::path::Path, args: &[&str]) {
    let output = Command::new("git")
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

fn git_stdout(dir: &std::path::Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .args(args)
        .current_dir(dir)
        .output()
        .unwrap();
    assert!(output.status.success(), "git {args:?} failed: {output:?}");
    String::from_utf8(output.stdout).unwrap().trim().to_string()
}

#[test]
fn policy_gates_are_worktree_relative() {
    let c = fleet_ctx();
    // THE REGRESSION (live 2026-08-18): ordinary work inside a worktree
    // that happens to sit under the fleet home must be ALLOWED. Denying it
    // left agents only relative-path shell editing — the one lane this
    // gate cannot check, i.e. the gate inverted its own purpose.
    assert_eq!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({"file_path": "/home/op/.cmctl/.foreman/task-5/src/crates/cosmix-foreman/src/refinery.rs"})
            )
        ),
        Verdict::Allow
    );
    // Bash naming the worktree absolutely is ordinary work too.
    assert_eq!(
        evaluate(
            &c,
            &call(
                "Bash",
                json!({"command": "cd /home/op/.cmctl/.foreman/task-5/src && cargo test -p cosmix-foreman"})
            )
        ),
        Verdict::Allow
    );
    // …while the enforcement rail stays denied at the same depth.
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({"file_path": "/home/op/.cmctl/.foreman/task-5/src/crates/cosmix-foreman/src/policy.rs"})
            )
        ),
        Verdict::Deny(_)
    ));
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Bash",
                json!({"command": "sed -i s/x/y/ /home/op/.cmctl/.foreman/task-5/src/crates/cosmix-foreman/src/policy.rs"})
            )
        ),
        Verdict::Deny(_)
    ));
    // A stray ledger nested INSIDE the worktree is still a gate.
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({"file_path": "/home/op/.cmctl/.foreman/task-5/.foreman/ledger.db"})
            )
        ),
        Verdict::Deny(_)
    ));
    // The FLEET's own ledger, outside the worktree: denied (gate first).
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({"file_path": "/home/op/.cmctl/.foreman/ledger.db"})
            )
        ),
        Verdict::Deny(_)
    ));
    // And a sibling task's worktree is outside THIS one: denied.
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({"file_path": "/home/op/.cmctl/.foreman/task-9/src/lib.rs"})
            )
        ),
        Verdict::Deny(_)
    ));
    // Prefix stripping must be COMPONENT-BOUNDARY aware: "task-5" is a
    // string-prefix of the sibling "task-50", whose .foreman/ protection a
    // blind replace would erase.
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Bash",
                json!({"command": "sed -i s/x/y/ /home/op/.cmctl/.foreman/task-50/src/lib.rs"})
            )
        ),
        Verdict::Deny(_)
    ));
    // …and must not strip a prefix whose remainder LEXICALLY ESCAPES the
    // worktree: this names the integration clone, which no name fragment
    // protects on its own.
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Bash",
                json!({"command": "git -C /home/op/.cmctl/.foreman/task-5/../workdir commit -am x"})
            )
        ),
        Verdict::Deny(_)
    ));
    // Escape detection reads the WHOLE path run, not just the first
    // component: these land on the integration clone too.
    for escaping in [
        "git -C /home/op/.cmctl/.foreman/task-5/./../workdir commit -am x",
        "git -C /home/op/.cmctl/.foreman/task-5/src/../../workdir commit -am x",
    ] {
        assert!(
            matches!(
                evaluate(&c, &call("Bash", json!({ "command": escaping }))),
                Verdict::Deny(_)
            ),
            "must not strip a prefix whose path run escapes: {escaping}"
        );
    }
    // The ordinary shell shape — worktree named, then more command — must
    // still pass (a boundary rule that broke this would re-break the fleet).
    assert_eq!(
        evaluate(
            &c,
            &call(
                "Bash",
                json!({"command": "cd /home/op/.cmctl/.foreman/task-5 && cargo fmt --check"})
            )
        ),
        Verdict::Allow
    );
}

#[test]
fn policy_write_containment() {
    let c = ctx("anthropic", Some("task/7"));
    // Inside the worktree: allowed.
    assert_eq!(
        evaluate(
            &c,
            &call("Write", json!({"file_path": "/work/task7/src/lib.rs"}))
        ),
        Verdict::Allow
    );
    // Relative paths resolve against the worktree.
    assert_eq!(
        evaluate(&c, &call("Edit", json!({"file_path": "src/lib.rs"}))),
        Verdict::Allow
    );
    // Outside: denied.
    assert!(matches!(
        evaluate(&c, &call("Write", json!({"file_path": "/etc/passwd"}))),
        Verdict::Deny(_)
    ));
    // ../ escape from inside: denied.
    assert!(matches!(
        evaluate(
            &c,
            &call("Write", json!({"file_path": "/work/task7/../other/x.rs"}))
        ),
        Verdict::Deny(_)
    ));
    // The agent's own gates: denied even inside a worktree path.
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({"file_path": "/work/task7/crates/cosmix-foreman/src/policy.rs"})
            )
        ),
        Verdict::Deny(_)
    ));
    // …but ONLY the enforcement surface: the rest of the foreman crate is
    // ordinary work — the fleet's own backlog IS foreman development, and a
    // whole-crate gate made every such task impossible (2026-08-18).
    assert!(matches!(
        evaluate(
            &c,
            &call(
                "Write",
                json!({"file_path": "/work/task7/crates/cosmix-foreman/src/driver/claude.rs"})
            )
        ),
        Verdict::Allow
    ));
    // Manifest edits escalate (recorded for the operator).
    assert!(matches!(
        evaluate(
            &c,
            &call("Write", json!({"file_path": "/work/task7/Cargo.toml"}))
        ),
        Verdict::Escalate(_)
    ));
}

